import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ejs from "ejs";

const projectDirectory = fileURLToPath(new URL("../", import.meta.url));
const viewsDirectory = path.join(projectDirectory, "views");
const outputDirectory = path.join(projectDirectory, "generated");

const templateLocals = [
	"title",
	"categories",
	"uncategorizedCount",
	"items",
	"priceFormatter",
	"category",
	"item",
	"errors",
	"action",
	"submitLabel",
	"cancelUrl",
	"destinations",
	"hasItems",
	"selectedDestination",
	"message",
	"families",
	"family",
	"breadcrumbs",
];

function escapeHTML(value) {
	if (value === undefined || value === null) {
		return "";
	}

	const entities = {
		"&": "&amp;",
		"<": "&lt;",
		">": "&gt;",
		'"': "&#34;",
		"'": "&#39;",
	};

	return String(value).replace(/[&<>"']/g, (character) => entities[character]);
}

async function compileDirectory(directory) {
	const entries = await readdir(directory, { withFileTypes: true });
	const compiled = [];

	entries.sort((first, second) => first.name.localeCompare(second.name));

	for (const entry of entries) {
		const filePath = path.join(directory, entry.name);

		if (entry.isDirectory()) {
			compiled.push(...await compileDirectory(filePath));
			continue;
		}

		if (!entry.isFile() || !entry.name.endsWith(".ejs")) {
			continue;
		}

		const relativePath = path.relative(viewsDirectory, filePath);
		const templateName = relativePath
			.split(path.sep)
			.join("/")
			.replace(/\.ejs$/, "");

		const source = await readFile(filePath, "utf8");

		const template = new ejs.Template(source, {
			strict: true,
			_with: false,
			localsName: "locals",
			destructuredLocals: templateLocals,
			compileDebug: false,
			filename: relativePath,
		});

		// Generate and syntax-check the template body during the build.
		template.compile();

		compiled.push(
			`${JSON.stringify(templateName)}: function (locals, escapeFn = escapeHTML, include) {
${template.source}
}`,
		);
	}

	return compiled;
}

async function buildViews() {
	const compiled = await compileDirectory(viewsDirectory);

	if (compiled.length === 0) {
		throw new Error("No EJS templates found.");
	}

	const moduleSource = [
		"// Generated by scripts/buildViews.js. Do not edit directly.",
		escapeHTML.toString(),
		"const templates = {",
		compiled.join(",\n"),
		"};",
		"export default templates;",
		"",
	].join("\n");

	await mkdir(outputDirectory, { recursive: true });

	await writeFile(
		path.join(outputDirectory, "views.js"),
		moduleSource,
	);

	console.log(`Compiled ${compiled.length} EJS templates.`);
}

try {
	await buildViews();
} catch (error) {
	console.error("View build failed:", error.message);
	process.exitCode = 1;
}
